// Preserves the original single-argument call signature (t('someKey')) used
// throughout the app — reads the current language off the global state S,
// exactly like the original: falls back to English, then the raw key itself.
const DICT_LOOKUP = DICT as Record<string, Record<string, string>>;

export function t(k: string): string {
  const d: Record<string, string> = DICT_LOOKUP[S.lang] || DICT_LOOKUP.en || {};
  const en: Record<string, string> = DICT_LOOKUP.en || {};
  return d[k] != null ? d[k] : en[k] != null ? en[k] : k;
}
